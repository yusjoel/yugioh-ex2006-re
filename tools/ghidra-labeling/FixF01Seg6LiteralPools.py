def _addr(v):
    return currentProgram.getAddressFactory().getDefaultAddressSpace().getAddress(v)


def _check(slot_addr, expected_val):
    mem = currentProgram.getMemory()
    a = _addr(slot_addr)
    try:
        actual = mem.getInt(a) & 0xFFFFFFFF
    except Exception as e:
        return False, "read error: %s" % e
    if actual != (expected_val & 0xFFFFFFFF):
        return False, "got 0x%08x expected 0x%08x" % (actual, expected_val & 0xFFFFFFFF)
    return True, "ok"


def _apply_dword(slot_addr, expected_val):
    a = _addr(slot_addr)
    listing = currentProgram.getListing()

    ok, msg = _check(slot_addr, expected_val)
    if not ok:
        print("[FAIL] 0x%08x: %s" % (slot_addr, msg))
        return False

    if DRY:
        print("[dry] DWORD 0x%08x  0x%08x" % (slot_addr, expected_val))
        return True

    try:
        listing.clearCodeUnits(a, a.add(3), False)
    except Exception as e:
        print("[WARN] clearCodeUnits 0x%08x: %s" % (slot_addr, e))

    try:
        dt = DWordDataType.dataType
        listing.createData(a, dt)
        return True
    except Exception as e:
        print("[WARN] createData 0x%08x: %s" % (slot_addr, e))
        return False


def main():
    print("=== FixF01Seg6LiteralPools (DRY=%s) ===" % DRY)
    print("  Fixing %d literal pool targets in 4 blocks" % len(LITERAL_POOL_TARGETS))

    ok_count = 0
    fail_count = 0

    for slot_addr, expected_val in LITERAL_POOL_TARGETS:
        if _apply_dword(slot_addr, expected_val):
            ok_count += 1
            if not DRY:
                print("[DWD] 0x%08x = 0x%08x" % (slot_addr, expected_val))
        else:
            fail_count += 1

    print("\n=== FixF01Seg6LiteralPools DONE ===")
    print("  ok=%d  fail=%d  total=%d" % (ok_count, fail_count, len(LITERAL_POOL_TARGETS)))
    if fail_count > 0:
        print("  [WARN] %d failures -- check value mismatches above" % fail_count)


main()
