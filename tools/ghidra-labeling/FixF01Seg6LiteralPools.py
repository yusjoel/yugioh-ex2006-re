# FixF01Seg6LiteralPools.py -- f01 Seg-6 literal pool fix
#   After DisassembleF01Seg6Blocks.py runs, the flow-based disassembler
#   may decode literal pool entries (ldr [pc,#X] targets within blocks)
#   as THUMB instructions rather than data. This script forces createDWord
#   on all 334 literal pool targets within the 4 disassembled blocks,
#   ensuring the GAS exporter emits ".word" instead of instruction mnemonics.
#
#   Literal pool targets identified by scanning all ldr [pc,#imm8] instructions
#   in blocks B1/B2/B3/B4 and checking which targets fall WITHIN those blocks.
#
#   Pattern: DWORD_SLOTS from RefineSeg10Slots.py
#   - clearCodeUnits at each target addr (4 bytes)
#   - createData DWord
#   - verify expected value matches ROM

